def new_img(w, h):
    """Create a new RGBA image with fully transparent background."""
    return Image.new("RGBA", (w, h), TRANSPARENT)


def put(img, x, y, color):
    """Place a single pixel (safe bounds check)."""
    if 0 <= x < img.width and 0 <= y < img.height:
        img.putpixel((x, y), color)


def draw_grid(img, grid, palette, ox=0, oy=0):
    """Draw a 2D grid of palette indices onto img at offset (ox, oy)."""
    for ry, row in enumerate(grid):
        for rx, idx in enumerate(row):
            if idx > 0 and idx < len(palette):
                put(img, ox + rx, oy + ry, palette[idx])


def scale_nn(img, factor):
    """Nearest-neighbor scale by integer factor."""
    return img.resize((img.width * factor, img.height * factor), Image.NEAREST)


